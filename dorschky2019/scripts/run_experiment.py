"""
Run one participant/stage config, generated by build_configs.py.

Each config in configs/{subject}/ is fully self-contained (model path, output
path, initial-guess chain, IMU data source, gait-cycle duration) -- this
script does no patching, it just registers the custom IMUTrackingObjective
and calls Collocation(...).solve().

Usage:
    python scripts/run_experiment.py P02 ig_standing
    python scripts/run_experiment.py P02 ig_standing --restarts 5
    python scripts/run_experiment.py P02 ig_walking
    python scripts/run_experiment.py P02 normwalking
"""
import argparse
import os
import sys

import cloudpickle

PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(PROJECT_DIR, "src"))

# Configs use paths relative to PROJECT_DIR (see build_configs.py); chdir here
# so they resolve correctly no matter where this script was invoked from.
os.chdir(PROJECT_DIR)

import track_imu  # noqa: E402
import biosym.ocp.objfun as boo  # noqa: E402
from biosym.ocp import collocation  # noqa: E402

# Need to add the IMU tracking objective to the biosym.ocp.objfun module so that the YAML config can find it.
boo.IMUTrackingObjective = track_imu

# IPOPT status codes accepted as a valid candidate solution when comparing
# restarts: 0 = solved to full tolerance, 1 = solved to the (looser)
# "acceptable" tolerance. Anything else (e.g. 2 = infeasible) is only used as
# a last resort if no restart converged at all.
_CONVERGED_STATUSES = {0, 1}


def _run_once(config_path, visualize):
    ocp = collocation.Collocation(config_path)
    sol = ocp.solve(visualize=visualize)
    return ocp, sol


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("subject", help="Participant ID, e.g. P02")
    parser.add_argument("stage", help="Config name (without .yaml): ig_standing, ig_walking, or a trial type")
    parser.add_argument("--visualize", action="store_true", help="Show plots of the solution (default: False)")
    parser.add_argument(
        "--restarts", type=int, default=1,
        help="Number of independent solves to run, keeping the lowest-objective converged "
             "result (default: 1, i.e. no restarts). Only useful for stages whose "
             "initial_guess type is 'random' (e.g. ig_standing) -- a deterministic "
             "from_file warm start gives identical results on every restart.",
    )
    args = parser.parse_args()

    config_path = os.path.join("configs", args.subject, f"{args.stage}.yaml")

    if args.restarts <= 1:
        ocp, sol = _run_once(config_path, args.visualize)
        info = sol.info
        print(f"\n=== {args.subject}/{args.stage} complete ===")
        print(f"IPOPT status: {info.get('status_msg')}")
        print(f"Final objective: {info.get('obj_val')}")
        return

    best = None  # (obj_val, converged, ocp, sol)
    for i in range(args.restarts):
        print(f"\n--- {args.subject}/{args.stage} restart {i + 1}/{args.restarts} ---")
        ocp, sol = _run_once(config_path, args.visualize)
        obj_val = sol.info.get("obj_val")
        converged = sol.info.get("status") in _CONVERGED_STATUSES
        print(f"restart {i + 1}: status={sol.info.get('status_msg')} obj_val={obj_val}")

        is_better = best is None or (
            (converged, -obj_val) > (best[1], -best[0])
        )
        if is_better:
            best = (obj_val, converged, ocp, sol)

    best_obj_val, best_converged, best_ocp, best_sol = best
    if not best_converged:
        print(f"\nWarning: none of the {args.restarts} restarts converged; keeping the "
              f"lowest-objective attempt anyway (status={best_sol.info.get('status_msg')}).")

    out_file = os.path.expanduser(best_ocp.settings["settings"]["output"]["file"])
    print(f"\nBest of {args.restarts} restarts: obj_val={best_obj_val} (status={best_sol.info.get('status_msg')})")
    print(f"Re-saving best result to {out_file}")
    os.makedirs(os.path.dirname(out_file), exist_ok=True)
    with open(out_file, "wb") as f:
        cloudpickle.dump((best_ocp.x, best_sol.info, best_ocp.settings), f)

    print(f"\n=== {args.subject}/{args.stage} complete ===")
    print(f"IPOPT status: {best_sol.info.get('status_msg')}")
    print(f"Final objective: {best_obj_val}")


if __name__ == "__main__":
    main()
